export function packageLaw(key) {
  return PACKAGE_LAW[key] || PACKAGE_LAW[Number(key)] || null;
}

function officialBody(key, ar) {
  const id = String(key);
  if (id === "3337") return ar ? DECISION_3337_TEXT_AR : DECISION_3337_TEXT_EN;
  if (id === "18632") return decision18632Body(ar);
  if (/^\d+$/.test(id)) {
    const official = articleOfficialText(id);
    if (!official) return "";
    return ar ? official.ar : official.en;
  }
  return "";
}

/** Fuller of the package paragraph and the stored official text. */
export function visibleStatute(key, ar = true) {
  const id = String(key);
  const pack = packageLaw(key);
  const packageText = pack?.[1] || "";
  const official = officialBody(key, ar);
  const useOfficial = !!official && official.length > packageText.length;
  const label = id === "3337"
    ? (ar ? "القرار 3337" : "Decision 3337")
    : id === "18632"
      ? (ar ? "قرار 18632" : "Decision 18632")
      : id === "نطاقات"
        ? (ar ? "نطاقات" : "Nitaqat")
        : /^\d+$/.test(id)
          ? (ar ? `المادة ${id}` : `Art. ${id}`)
          : (pack?.[0] || "—");
  return {
    key: id,
    label,
    title: pack?.[0] || "",
    text: (useOfficial ? official : packageText) || "—",
    packageText: packageText || "—",
    usedOfficial: useOfficial,
  };
}

const DASH = { label: "—", tone: "idle", detail: "—" };

export function ruleStatus(rule, ctx = {}, ar = true) {
  if (!rule) return DASH;
  if (rule.kind === "nitaqat") {
    const label = ctx.nitaqatLabel;
    if (!label || label === "—") return DASH;
    return { label, tone: "ok", detail: label };
  }
  if (rule.kind === "gosi") {
    if (ctx.gosiLinked == null) return DASH;
    return ctx.gosiLinked
      ? { label: ar ? "مرتبط" : "Linked", tone: "ok", detail: "—" }
      : { label: ar ? "قيد الربط" : "Not linked", tone: "warn", detail: "—" };
  }
  if (rule.kind === "mudad") {
    if (ctx.mudadLinked == null) return DASH;
    return ctx.mudadLinked
      ? { label: ar ? "مرتبط" : "Linked", tone: "ok", detail: "—" }
      : { label: "—", tone: "idle", detail: "—" };
  }
  if (rule.kind === "maternity") {
    return ctx.maternityReady
      ? { label: ar ? "مستوفٍ" : "Met", tone: "ok", detail: "—" }
      : DASH;
  }
  const ids = rule.gates || (rule.gate ? [rule.gate] : []);
  if (!ids.length) return DASH;
  const found = ids.map((id) => (ctx.checks || []).find((row) => row.id === id)).filter(Boolean);
  if (!found.length) return DASH;
  const blocked = found.find((row) => row.ok === false && row.block);
  const warned = found.find((row) => row.ok === false);
  const hit = blocked || warned || found[0];
  if (hit.ok) {
    const offSeason = /خارج/.test(String(hit.note || ""));
    return {
      label: offSeason ? (ar ? "خارج الموسم" : "Off season") : (ar ? "مستوفٍ" : "Met"),
      tone: offSeason ? "idle" : "ok",
      detail: hit.note || "—",
    };
  }
  return {
    label: blocked ? (ar ? "مخالفة" : "Breach") : (ar ? "تنبيه" : "Note"),
    tone: blocked ? "bad" : "warn",
    detail: hit.note || "—",
  };
}

export function catalogSummary(rows, ctx, ar = true) {
  const statuses = (rows || []).map((rule) => ruleStatus(rule, ctx, ar));
  const known = statuses.filter((row) => row.label !== "—");
  const action = statuses.filter((row) => row.tone === "bad" || row.tone === "warn");
  const applied = statuses.filter((row) => row.label !== "—" && row.tone !== "bad" && row.tone !== "warn");
  if (!known.length) {
    return { applied: "—", action: "—", rate: "—" };
  }
  const total = rows.length;
  return {
    applied: `${applied.length} / ${total}`,
    action: String(action.length),
    rate: `${Math.round((applied.length / total) * 100)}%`,
  };
}

