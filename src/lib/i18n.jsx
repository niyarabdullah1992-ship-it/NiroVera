const I18nContext = createContext(null);

const GENERATED_VERSION = "v3";
const GENERATED_KEY = `powercare_generated_translations_${GENERATED_VERSION}`;
const PRESERVED_KEYS = new Set(["dir", "appName", "plan_starter", "plan_pro", "plan_ent"]);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const saved = localStorage.getItem("powercare_lang");
    // Arabic-first product default when no preference is stored.
    return saved === "ar" || saved === "en" ? saved : "ar";
  });
  const [generated, setGenerated] = useState(() => {
    try { return JSON.parse(localStorage.getItem(GENERATED_KEY) || "{}"); } catch { return {}; }
  });
  const [isTranslating, setIsTranslating] = useState(false);
  const t = (key) => {
    if (lang === "en") return dict.en[key] ?? key;
    const staticVal = dict[lang]?.[key];
    // Static translation that actually differs from English wins
    if (staticVal !== undefined && staticVal !== dict.en[key]) return staticVal;
    const gen = generated[lang]?.[key];
    if (gen) return gen;
    // Never show "…" — fall back to English until the translation arrives
    return staticVal ?? dict.en[key] ?? key;
  };
  const dir = dict[lang]?.dir || "ltr";

  useEffect(() => {
    localStorage.setItem("powercare_lang", lang);
    document.documentElement.dir = dir;
    document.documentElement.lang = lang;
  }, [lang, dir]);

  useEffect(() => {
    if (lang === "en") return;
    // Every key still shown in English for this language (no static or generated translation)
    const missing = Object.entries(dict.en).filter(([key, value]) => !PRESERVED_KEYS.has(key) && !generated[lang]?.[key] && (!dict[lang]?.[key] || dict[lang][key] === value));
    if (!missing.length) return;
    let cancelled = false;
    setIsTranslating(true);

    (async () => {
      try {
        // Server-side translation: generated once, cached in the cloud for all users
        const res = await base44.functions.invoke("uiTranslations", {
          lang,
          langLabel: LANGUAGES.find((item) => item.code === lang)?.label,
          keys: Object.fromEntries(missing),
        });
        const translations = res.data?.translations;
        if (translations && !cancelled) {
          const clean = Object.fromEntries(
            Object.entries(translations).filter(
              ([k, v]) => typeof v === "string" && v.trim() && k in dict.en
            )
          );
          setGenerated((current) => {
            const next = { ...current, [lang]: { ...(current[lang] || {}), ...clean } };
            localStorage.setItem(GENERATED_KEY, JSON.stringify(next));
            return next;
          });
        }
      } catch {
        // Server unavailable — English fallback stays visible
      }
      if (!cancelled) setIsTranslating(false);
    })();

    return () => {
      cancelled = true;
      setIsTranslating(false);
    };
  }, [lang]);

  return (
    <I18nContext.Provider value={{ lang, setLang, t, dir, languages: LANGUAGES, isTranslating }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}