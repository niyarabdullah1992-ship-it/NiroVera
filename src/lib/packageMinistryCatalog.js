/** One week-gate pack per station in scope. A failing station wins. */
export function mergeStationWeekChecks({
  data,
  stations = [],
  employees = [],
  laborCalendar,
  ar = true,
  today,
} = {}) {
  const byId = new Map();
  const start = weekStartDate(today || new Date());
  for (const station of stations) {
    if (!station?.id) continue;
    const schedule = (data?.schedules || []).find((row) => String(row.stationId) === String(station.id))
      || { stationId: station.id, shiftTypes: [], assignments: {} };
    const gates = checkWeekPublishGates({
      schedule,
      employees,
      weekStart: start,
      stationId: station.id,
      station,
      settings: data?.settings,
      company: data,
      ar,
      laborCalendar,
      today: today || new Date(),
    });
    for (const check of gates.checks || []) {
      const prev = byId.get(check.id);
      if (!prev) byId.set(check.id, { ...check });
      else if (check.ok === false) {
        prev.ok = false;
        prev.block = !!(prev.block || check.block);
        prev.note = check.note || prev.note;
      }
    }
  }
  return { checks: [...byId.values()] };
}
